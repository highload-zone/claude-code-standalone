#!/usr/bin/env bash
set -euo pipefail

# Render the shared MCP server set (mcp-servers.json + mcp-servers-optional.json)
# into the config format of one agent. One source of truth, three renderings:
#
#   claude   -> ~/.claude.json  .projects["/workspace/project"].mcpServers  (native format)
#   codex    -> ~/.codex/config.toml  [mcp_servers.<id>...]   (stdio | streamable HTTP)
#   opencode -> ~/.config/opencode/opencode.json  { "mcp": { <id>: { local | remote } } }
#
# Secrets never get baked. A value written as ${VAR} in the source:
#   claude   keeps the literal ${VAR} (Claude Code expands it at connect time);
#   codex    becomes env_vars = ["VAR"] / env_http_headers = { HDR = "VAR" };
#   opencode becomes {env:VAR}.
# That way the same key works at runtime for all three agents and no token is
# ever written to an image layer.

AGENT="${1:-}"
MCP_SERVERS_FILE="${MCP_SERVERS_FILE:-/app/mcp-servers.json}"
MCP_OPTIONAL_FILE="${MCP_OPTIONAL_FILE:-/app/mcp-servers-optional.json}"

case "$AGENT" in
  claude|codex|opencode) ;;
  *) echo "usage: $0 <claude|codex|opencode>" >&2; exit 2;;
esac

for f in "$MCP_SERVERS_FILE" "$MCP_OPTIONAL_FILE"; do
  [ -f "$f" ] || { echo "missing MCP config: $f" >&2; exit 1; }
done

# --- Merge base servers with the optional ones (only when their env vars are set) ---
merge_servers() {
  local merged optional
  merged="$(cat "$MCP_SERVERS_FILE")"
  optional="$(jq -c 'keys[]' "$MCP_OPTIONAL_FILE")"
  for name in $optional; do
    local config
    config="$(jq -c --arg n "$name" '.[$n]' "$MCP_OPTIONAL_FILE")"
    # Collect every ${VAR} in this server; skip the whole server if any is unset.
    local vars ok=1
    vars="$(jq -r '[.. | strings | select(test("^\\$\\{[A-Za-z_][A-Za-z0-9_]*\\}$"))] | unique | .[]' <<<"$config")"
    for v in $vars; do
      local var="${v#\$\{}"; var="${var%\}}"
      if [ -z "${!var:-}" ]; then ok=0; break; fi
    done
    if [ "$ok" = "1" ]; then
      echo "  + optional server: $name" >&2
      merged="$(jq -c --arg n "$name" --argjson c "$config" '. + {($n): $c}' <<<"$merged")"
    else
      echo "  - skipped (unset env): $name" >&2
    fi
  done
  printf '%s' "$merged"
}

# jq helpers shared by the TOML/JSON renderers. A value is a "reference" when it
# is exactly ${NAME}; NAME is then carried over as an env var name instead of a value.
JQ_REF='^\$\{[A-Za-z_][A-Za-z0-9_]*\}$'
JQ_REFNAME='^\$\{(?<n>[A-Za-z_][A-Za-z0-9_]*)\}$'

# TOML string / array / inline table formatters (JSON string escaping is valid TOML).
# `-r` is required: @json returns the encoded text as a jq string, so without raw
# output the surrounding quotes get escaped a second time by jq's serializer.
toml_str()   { jq -Rn -r --arg v "$1" '$v|@json'; }
toml_array() { jq -rc '.'; }
toml_inline() {
  # $1 = [{key, value}] -> { KEY = "value", ... }
  jq -rc 'map("\(.key) = \(.value|@json)") | "{ " + join(", ") + " }"'
}

render_codex() {
  local cfg="$HOME/.codex/config.toml"
  mkdir -p "$(dirname "$cfg")"
  {
    echo "# Generated by render-mcp-configs.sh from mcp-servers.json — do not edit."
    echo "# Remote updates are off so the image stays pinned."
    echo 'check_for_update_on_startup = false'
    echo
    local name
    for name in $(jq -r 'keys[]' <<<"$MERGED"); do
      local obj url
      obj="$(jq -c --arg n "$name" '.[$n]' <<<"$MERGED")"
      url="$(jq -r '.url // empty' <<<"$obj")"
      echo "[mcp_servers.$name]"
      if [ -n "$url" ]; then
        printf 'url = %s\n' "$(toml_str "$url")"
        local env_hdrs http_hdrs
        env_hdrs="$(jq -c --arg ref "$JQ_REF" --arg refname "$JQ_REFNAME" \
          '[ (.headers // {}) | to_entries[] | select(.value|test($ref)) | {key: .key, value: (.value|capture($refname).n)} ]' <<<"$obj")"
        http_hdrs="$(jq -c --arg ref "$JQ_REF" \
          '[ (.headers // {}) | to_entries[] | select(.value|test($ref)|not) | {key: .key, value: .value} ]' <<<"$obj")"
        [ "$(jq 'length' <<<"$env_hdrs")" -gt 0 ] && printf 'env_http_headers = %s\n' "$(toml_inline <<<"$env_hdrs")"
        [ "$(jq 'length' <<<"$http_hdrs")" -gt 0 ] && printf 'http_headers = %s\n' "$(toml_inline <<<"$http_hdrs")"
      else
        printf 'command = %s\n' "$(toml_str "$(jq -r '.command' <<<"$obj")")"
        local args
        args="$(jq -c '.args // []' <<<"$obj")"
        [ "$(jq 'length' <<<"$args")" -gt 0 ] && printf 'args = %s\n' "$(toml_array <<<"$args")"
        local env_vars env_lit
        env_vars="$(jq -c --arg ref "$JQ_REF" --arg refname "$JQ_REFNAME" \
          '[ (.env // {}) | to_entries[] | select(.value|test($ref)) | .value|capture($refname).n ]' <<<"$obj")"
        env_lit="$(jq -c --arg ref "$JQ_REF" \
          '[ (.env // {}) | to_entries[] | select(.value|test($ref)|not) | {key: .key, value: .value} ]' <<<"$obj")"
        [ "$(jq 'length' <<<"$env_vars")" -gt 0 ] && printf 'env_vars = %s\n' "$(toml_array <<<"$env_vars")"
        [ "$(jq 'length' <<<"$env_lit")" -gt 0 ] && printf 'env = %s\n' "$(toml_inline <<<"$env_lit")"
      fi
      echo
    done
  } > "$cfg"
  echo "wrote $cfg"
}

render_opencode() {
  local cfg="$HOME/.config/opencode/opencode.json"
  mkdir -p "$(dirname "$cfg")"
  # ${VAR} -> {env:VAR} for opencode's own env substitution; literal stays literal.
  jq -n --arg ref "$JQ_REF" --arg refname "$JQ_REFNAME" --argjson MERGED "$MERGED" '
    def envref: if test($ref) then (capture($refname).n) | "{env:\(.)}" else . end;
    def conv(o): (o // {}) | to_entries | map({key: .key, value: (.value|envref)}) | from_entries;
    {
      "$schema": "https://opencode.ai/config.json",
      autoupdate: false,
      mcp: (
        reduce ($MERGED | to_entries[]) as $e ({};
          if ($e.value.url // null) then
            .[$e.key] = ({type: "remote", url: $e.value.url, enabled: true}
              + (if (($e.value.headers // {}) | length) > 0 then {headers: conv($e.value.headers)} else {} end))
          else
            .[$e.key] = ({type: "local", command: ([$e.value.command] + ($e.value.args // [])), enabled: true}
              + (if (($e.value.env // {}) | length) > 0 then {environment: conv($e.value.env)} else {} end))
          end)
      )
    }
  ' > "$cfg"
  echo "wrote $cfg"
}

render_claude() {
  local cfg="$HOME/.claude.json"
  [ -f "$cfg" ] || { echo "missing Claude config: $cfg" >&2; exit 1; }
  jq --argjson servers "$MERGED" \
    '.projects["/workspace/project"].mcpServers = $servers' \
    "$cfg" > "${cfg}.tmp"
  mv "${cfg}.tmp" "$cfg"
  echo "wrote $cfg (.projects[\"/workspace/project\"].mcpServers)"
}

echo "Rendering MCP servers for: $AGENT"
MERGED="$(merge_servers)"
case "$AGENT" in
  claude)   render_claude;;
  codex)    render_codex;;
  opencode) render_opencode;;
esac
echo "MCP servers:"
jq -r 'keys[]' <<<"$MERGED" | sed 's/^/  - /'